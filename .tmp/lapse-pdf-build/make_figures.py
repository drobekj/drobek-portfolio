durations = ['6-9', '10', '11', '12', '13+']
rates = np.array([0.066546, 0.582550, 0.296048, 0.112397, 0.070038])
fig, ax = plt.subplots(figsize=(7.2, 4.2))
ax.bar(durations, rates * 100)
ax.set_ylabel('Lapse rate (%)')
ax.set_xlabel('Policy duration')
ax.set_title('Lapse rate by policy duration')
ax.set_ylim(0, 65)
ax.grid(axis='y', alpha=0.25)
for i, v in enumerate(rates * 100):
    ax.text(i, v + 1.2, f'{v:.1f}%', ha='center', va='bottom', fontsize=9)
fig.tight_layout()
fig.savefig(out / '01_lapse_rate_by_duration.pdf', bbox_inches='tight')
plt.close(fig)

